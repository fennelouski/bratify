def build_strings_content(locale):
    values = TRANSLATIONS[locale]
    lines = []
    for key, value in zip(KEYS, values):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'"{key}" = "{escaped}";')
    return "\n".join(lines) + "\n"


written = 0
for locale, _ in TRANSLATIONS.items():
    lproj_dir = os.path.join(BASE, f"{locale}.lproj")
    os.makedirs(lproj_dir, exist_ok=True)
    path = os.path.join(lproj_dir, "Localizable.strings")
    content = build_strings_content(locale)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    written += 1
    print(f"  wrote {locale}.lproj/Localizable.strings")

print(f"\nDone: wrote {written} locale files.")
