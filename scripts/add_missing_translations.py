# Fix eli5 dict comprehension (can't use comprehension in dict literal)
TRANSLATIONS["eli5"] = {loc: "eli5" for loc in LOCALES}

def main():
    with open(XCSTRINGS_PATH, encoding="utf-8") as f:
        data = json.load(f)

    strings = data["strings"]
    updated_count = 0

    for key, translations in TRANSLATIONS.items():
        if key not in strings:
            print(f"WARNING: key {repr(key)} not found in xcstrings", file=sys.stderr)
            continue
        entry = strings[key]
        if "localizations" not in entry:
            entry["localizations"] = {}
        locs = entry["localizations"]
        for locale, value in translations.items():
            if locale not in locs:
                locs[locale] = {
                    "stringUnit": {
                        "state": "translated",
                        "value": value
                    }
                }
                updated_count += 1

    print(f"Added {updated_count} translations")

    with open(XCSTRINGS_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False, separators=(",", " : "))
        f.write("\n")

    print("Done writing xcstrings")

if __name__ == "__main__":
    main()
